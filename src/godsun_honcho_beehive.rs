/// and an $n$-dimensional `plasma-hqt/n` phase vector from the bidirectional USB-C bus state
/// and `[standardgalactic:LAST_10_COMMITS<<<ULTRA-OMNI-GODSUN`.
pub fn generate_usbc_bidirect_rand_pq_seed(
    extra_entropy_phrase: &str,
    plasma_dim_n: usize,
) -> RandRandPqSeed {
    let (live_ok, endpoints) = probe_usbc_bidirect_endpoints();
    let commits = standardgalactic_last_10_commits();

    let mut hasher = Sha256::new();
    hasher.update(b"USBC-BIDIRECT::randRandPq::quanT::plasma-hqt/n::ULTRA-OMNI-GODSUN::");
    hasher.update(extra_entropy_phrase.as_bytes());
    for ep in &endpoints {
        hasher.update(ep.name.as_bytes());
        hasher.update(ep.location_id_hex.as_bytes());
        hasher.update(ep.bus_controller.as_bytes());
        // Anchor structural topology (`retain_count`) deterministically while recording `busy_ms`
        hasher.update(ep.retain_count.to_le_bytes());
    }
    for c in &commits {
        hasher.update(c.sha_short.as_bytes());
        hasher.update([c.trit_bias as u8]);
    }
    let digest = hasher.finalize();
    let sha256_seed_hex: String = digest.iter().map(|b| format!("{b:02x}")).collect();

    let mut raw_p = u64::from_le_bytes(digest[0..8].try_into().unwrap()) | 1;
    let raw_q = (u64::from_le_bytes(digest[8..16].try_into().unwrap()) & 0x7FFF_FFFF_FFFF_FFFF) | 3;
    if raw_p == raw_q {
        raw_p = raw_p.wrapping_add(432);
    }
    let g = gcd_u64(raw_p, raw_q);
    let numerator_p = raw_p / g;
    let denominator_q = (raw_q / g).max(1);
    let gcd_verified_one = gcd_u64(numerator_p, denominator_q) == 1;

    // 27-trit `quanT` signature unpacked from digest bytes
    let mut quant_trits_27 = [0i8; 27];
    for (idx, slot) in quant_trits_27.iter_mut().enumerate() {
        let b = digest[idx % 32];
        let raw_signed = ((b.rotate_left((idx % 7) as u32) as i16) % 3) - 1;
        *slot = clamp_ternary!(raw_signed) as i8;
    }

    let vad = qwave_core::quanttern::Vad::new(
        (quant_trits_27[0] as f32) * 0.8 + 0.16,
        (quant_trits_27[1] as f32) * 0.8 + 0.16,
        (quant_trits_27[2] as f32) * 0.8 + 0.16,
    );
    let emo = qwave_core::quanttern::encode(vad, qwave_core::quanttern::DEFAULT_THRESHOLD);
    let quanttern_4trit_tag = emo.hex;

    // `plasma-hqt/n`: n-dimensional Hyper-Quantum-Ternary phase vector in Q16 fixed-point
    let dim_n = plasma_dim_n.clamp(4, 64);
    let mut plasma_hqt_n_vector_q16 = Vec::with_capacity(dim_n);
    let mut state = numerator_p ^ denominator_q.rotate_left(13);
    for d in 0..dim_n {
        state = state
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407 ^ (d as u64 * 432));
        let trit = quant_trits_27[d % 27] as i64;
        let harmonic_q16 = ((state >> 16) & 0xFFFF) as i64;
        // Phase-modulate by balanced ternary polarity + 432/528 rational ratio
        let val_q16 = if trit == 0 {
            harmonic_q16 / 2
        } else {
            trit * harmonic_q16
        };
        plasma_hqt_n_vector_q16.push(val_q16);
    }

    let qat_31_32_reuse_slot = ((popcount!(numerator_p ^ denominator_q) % 31) + 1) as u8;

    RandRandPqSeed {
        generator_id: "USBC-BIDIRECT::randRandPq::v1.0-RationalPQ".to_string(),
        hardware_probed_live: live_ok,
        usbc_endpoints: endpoints,
        numerator_p,
        denominator_q,
        gcd_verified_one,
        rational_pq_str: format!("{numerator_p}/{denominator_q}"),
        qat_31_32_reuse_slot,
        quant_trits_27,
        quanttern_4trit_tag,
        plasma_hqt_dimension_n: dim_n,
        plasma_hqt_n_vector_q16,
        sha256_seed_hex,
    }
}

